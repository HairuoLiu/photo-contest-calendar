/** Maps a browser language base code (e.g. "en", "zh", "pt") to a supported Lang. */
const REGION_FALLBACK: Record<string, Lang> = {
  en: 'en',
  zh: 'zh-CN',
  ja: 'ja',
  ko: 'ko',
  es: 'es',
  fr: 'fr',
  de: 'de',
  pt: 'pt',
  ru: 'ru',
  it: 'it',
  nl: 'nl',
  th: 'th',
  vi: 'vi',
  id: 'id',
  ms: 'ms',
}

function normalizeLang(s: string): Lang | null {
  const lower = s.toLowerCase()
  const exact = LANGS.find((l) => l.code.toLowerCase() === lower)
  if (exact) return exact.code
  const base = lower.split('-')[0]
  return REGION_FALLBACK[base] ?? null
}

/** Pick the best supported language from the browser's full preference list,
 *  falling back to English. Reads navigator.languages (priority-ordered) so we
 *  honor the user's daily language even when it's not their top OS locale. */
export function detectLang(): Lang {
  if (typeof navigator === 'undefined') return 'en'
  const prefs =
    navigator.languages && navigator.languages.length
      ? navigator.languages
      : [navigator.language]
  for (const p of prefs) {
    const hit = normalizeLang(p)
    if (hit) return hit
  }
  return 'en'
}

